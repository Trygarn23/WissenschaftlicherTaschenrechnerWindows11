package modes.graph.model;

public class GraphPunkt
{
    private final double x;
    private final double y;

    public GraphPunkt(double x, double y)
    {
        this.x = x;
        this.y = y;
    }

    public double getX()
    {
        return x;
    }

    public double getY()
    {
        return y;
    }
}
